// Declarations renders a `.d.ts`-style block for the given namespaces. This is
// what `mcpx types` prints and what an agent pastes into its context: only the
// namespaces it asked for, nothing else.
func Declarations(nss []Namespace) string {
	var b strings.Builder
	b.WriteString("// Generated by mcpx. Call these from a script run with `mcpx run <file.ts>`.\n")
	b.WriteString("// Every function is async and returns the tool's result.\n\n")

	sort.Slice(nss, func(i, j int) bool { return nss[i].Name < nss[j].Name })
	for _, ns := range nss {
		if ns.Description != "" {
			b.WriteString("/** " + sanitizeComment(ns.Description) + " */\n")
		}
		fmt.Fprintf(&b, "declare namespace %s {\n", ns.Name)
		tools := append([]Tool(nil), ns.Tools...)
		sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
		for i, t := range tools {
			if i > 0 {
				b.WriteString("\n")
			}
			b.WriteString(toolDecl(t, "  "))
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

func toolDecl(t Tool, indent string) string {
	var b strings.Builder
	if d := strings.TrimSpace(t.Description); d != "" {
		lines := strings.Split(d, "\n")
		b.WriteString(indent + "/**\n")
		for _, l := range lines {
			b.WriteString(indent + " * " + sanitizeComment(l) + "\n")
		}
		b.WriteString(indent + " */\n")
	}
	argsType, optional := ArgsTypeFor(t.InputSchema, indent)
	opt := ""
	if optional {
		opt = "?"
	}
	fn := ToolFuncName(t.Name)
	fmt.Fprintf(&b, "%sfunction %s(args%s: %s): Promise<ToolResult>;\n", indent, fn, opt, argsType)
	return b.String()
}

// Module renders the importable client module. Scripts do:
//
//	import { fff, chrome_devtools } from "./.mcpx/client.ts";
//
// or use the default `tools` object. The module is written to disk, so the
// JavaScript runtime's own module cache applies and startup stays at tens of
// milliseconds.
func Module(nss []Namespace, endpoint, session string) string {
	var b strings.Builder
	b.WriteString(moduleHeader)
	fmt.Fprintf(&b, "const DEFAULT_ENDPOINT = %s;\n", quote(endpoint))
	fmt.Fprintf(&b, "const DEFAULT_SESSION = %s;\n\n", quote(session))
	b.WriteString(moduleRuntime)

	sort.Slice(nss, func(i, j int) bool { return nss[i].Name < nss[j].Name })

	for _, ns := range nss {
		tools := append([]Tool(nil), ns.Tools...)
		sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })

		if ns.Description != "" {
			b.WriteString("/** " + sanitizeComment(ns.Description) + " */\n")
		}
		fmt.Fprintf(&b, "export const %s = {\n", ns.Name)
		for i, t := range tools {
			if i > 0 {
				b.WriteString("\n")
			}
			b.WriteString(toolImpl(ns.Server, t, "  "))
		}
		b.WriteString("};\n\n")
	}

	b.WriteString("export const tools = {\n")
	for _, ns := range nss {
		fmt.Fprintf(&b, "  %s,\n", ns.Name)
	}
	b.WriteString("};\n\nexport default tools;\n")
	return b.String()
}

func toolImpl(server string, t Tool, indent string) string {
	var b strings.Builder
	if d := strings.TrimSpace(t.Description); d != "" {
		lines := strings.Split(d, "\n")
		b.WriteString(indent + "/**\n")
		for _, l := range lines {
			b.WriteString(indent + " * " + sanitizeComment(l) + "\n")
		}
		b.WriteString(indent + " */\n")
	}
	argsType, optional := ArgsTypeFor(t.InputSchema, indent)
	opt := ""
	if optional {
		opt = "?"
	}
	fn := ToolFuncName(t.Name)
	fmt.Fprintf(&b, "%s%s(args%s: %s): Promise<ToolResult> {\n", indent, fn, opt, argsType)
	fmt.Fprintf(&b, "%s  return __call(%s, %s, args);\n", indent, quote(server), quote(t.Name))
	fmt.Fprintf(&b, "%s},\n", indent)
	return b.String()
}

