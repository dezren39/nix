//
// Each function posts one tools/call to the local mcpx daemon, which owns the
// MCP server processes. Results are returned already unwrapped: a text-only
// result becomes a string, a structured result becomes the parsed object.
// Reach for .raw on the returned value when you need the full MCP envelope.

